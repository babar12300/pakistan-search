  Landmark,
  GraduationCap,
  Mountain,
  ShoppingBag,
  Banknote,
  Smartphone,
  Trophy,
  HeartPulse,
  Music,
  Globe,
  Briefcase,
  UtensilsCrossed,
  Car,
  House,
  Cpu,
  Shirt,
